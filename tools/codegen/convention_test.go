package codegen

import (
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// 拆开拼是为了让本文件自身不含这个字面量——否则 WalkDir 扫到自己会报错。
const codegenMark = "// Code " + "generated by"

// TestGeneratedFilesAreMarked 生成物的「命名」与「标识」必须一致：
//
//   - 带 CODEGEN 头的文件必须以 _gen.go 或 .pb.go 结尾；
//   - 以 _gen.go 结尾的文件必须带 CODEGEN 头。
//
// 为什么值得一条测试：两者不一致时，读代码的人只能靠打开文件看第一行才知道
// 「这个文件能不能改」。pkg/gamedata/data.go 曾经就是反例——它是全量覆盖的
// 生成物，但名字和手写的 tables.go 长得一样，改它等于白改。
//
// .pb.go 单独放行：protoc 的文件名由插件决定，改不了，且工具链自己认这个后缀。
func TestGeneratedFilesAreMarked(t *testing.T) {
	root := filepath.Join("..", "..")
	var checked int

	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "bin", "volumes", "node_modules", "deploy":
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") {
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}

		head := make([]byte, 200)
		f, err := os.Open(path)
		if err != nil {
			return err
		}
		n, _ := f.Read(head)
		f.Close()
		marked := strings.Contains(string(head[:n]), codegenMark)

		isGen := strings.HasSuffix(path, "_gen.go")
		isPB := strings.HasSuffix(path, ".pb.go")

		switch {
		case marked && !isGen && !isPB:
			t.Errorf("%s: 有 CODEGEN 头但不是 _gen.go / .pb.go —— 改名为 <名字>_gen.go，否则下一个人会以为可以手改", rel)
		case isGen && !marked:
			t.Errorf("%s: 是 _gen.go 却没有 `%s ... DO NOT EDIT.` 头 —— 生成物必须能一眼认出来", rel, codegenMark)
		}
		checked++
		return nil
	})
	if err != nil {
		t.Fatalf("扫描失败：%v", err)
	}
	if checked < 500 {
		t.Fatalf("只扫到 %d 个 go 文件，路径判断失效了", checked)
	}
}

// tools/gendb —— DDL → Go CRUD 生成器（设计文档 16.2，参考 goctl model）
//
// 工程链位置：`make gen` 一键生成的最后一环，对应 Makefile target `make gen-db`
// （= `go run ./tools/gendb -in sql/schema -out pkg/model`）；产物同样被 CI 的
// `make gen-check` 生成到临时目录后逐字节比对（与工作区状态无关）。
//
// 输入 sql/schema/*.sql（手写带注释 DDL），产出 pkg/model/：
//   - <table>_gen.go   结构体 + 列常量 + TableName + CRUD（全量覆盖，禁止手改）
//   - <table>_model.go 仅首次创建（自定义查询/复杂方法，见 16.4 覆盖策略）
//
// CRUD 基于 database/sql（? 占位符，MySQL 兼容）；UPSERT 使用
// INSERT ... ON DUPLICATE KEY UPDATE（落库幂等，18.2 防线②）。
package main

import (
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// column 一个解析出的列定义（DDL 行 → Go 字段的中间表示）。
//
// 三组名字各司其职：Name 是 SQL 原名（拼 SQL 语句用），GoName 是导出标识符
// （拼 Go 代码用），GoType 决定结构体字段与 Scan 目标的类型。
// 四个布尔标记全部来自 DDL 文本特征（AUTO_INCREMENT / NOT NULL /
// DEFAULT CURRENT_TIMESTAMP / 主键列表），决定生成哪些写路径。
type column struct {
	Name     string // 原名 snake_case
	GoName   string // CamelCase
	GoType   string // int64/int32/string/bool/float64/time.Time
	SQLType  string // 原始 SQL 类型
	NotNull  bool
	AutoInc  bool
	AutoTime bool // DEFAULT CURRENT_TIMESTAMP：时间由 DB 生成，写路径跳过该列
	IsPK     bool
}

// table 一张解析出的表。
// Name 是 SQL 表名；Columns 保 DDL 声明顺序（SELECT 列序、Scan 目标序都依赖它）；
// PKs 多列时按 DDL 顺序；FlatModule 非空 = 被 @flat 标注，见 parseSQL 的契约检查。
type table struct {
	Name    string
	Columns []column
	PKs     []string
	// FlatModule 非空表示该表被 @flat:<模块名> 标注为「玩家级单行状态表」，
	// 额外生成 flush.FlatOps 适配，供 writebehind.RegisterFlat 一行注册。
	FlatModule string
}

// main 入口：扫 sql/schema/*.sql → 解析表与 @flat 标注 → 生成 querier + 逐表 model。
//
// 表按名排序后生成：输出顺序稳定，make gen-check 的逐文件比对才不会误报。
//
// 错误策略：解析/生成失败一律 log.Fatal（日志走 stderr + 非零退出码）。
// Go 知识点：log.Fatal 内部调用 os.Exit(1)，其后的 defer 不会执行 ——
// 本工具没有需要清理的资源（未持连接/未加锁），直接退出优于层层返回 err。
func main() {
	in := flag.String("in", "sql/schema", "DDL 输入目录")
	out := flag.String("out", "pkg/model", "Go 代码输出目录")
	flag.Parse()

	entries, err := os.ReadDir(*in)
	if err != nil {
		log.Fatalf("read dir %s: %v", *in, err)
	}
	var tables []table
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		ts, err := parseSQL(filepath.Join(*in, e.Name()))
		if err != nil {
			log.Fatalf("parse %s: %v", e.Name(), err)
		}
		tables = append(tables, ts...)
	}
	// 排序保证生成顺序稳定：gen-check 与工作区状态无关，靠「生成到临时目录再逐文件比对」
	sort.Slice(tables, func(i, j int) bool { return tables[i].Name < tables[j].Name })

	if err := os.MkdirAll(*out, 0o755); err != nil {
		log.Fatalf("mkdir %s: %v", *out, err)
	}
	if err := genQuerier(*out); err != nil {
		log.Fatalf("gen querier: %v", err)
	}
	for _, t := range tables {
		if err := genModel(*out, t); err != nil {
			log.Fatalf("gen %s: %v", t.Name, err)
		}
		fmt.Printf("  %-24s → %s_gen.go（%d 列，PK: %s%s）\n",
			t.Name+".sql", t.Name, len(t.Columns), strings.Join(t.PKs, "+"), flatSuffix(t))
	}
	fmt.Printf("gendb 完成：%d 张表 → %s\n", len(tables), *out)
}

// createTableRe 匹配一条 CREATE TABLE，抓表名与括号内的列定义段。
//
// (?is)：. 跨行 + 忽略大小写；列段用非贪婪 (.*?) 并以 ENGINE/COMMENT/DEFAULT/; 收尾，
// 覆盖「无 ENGINE 子句的 DDL」；表名允许反引号/双引号包裹两种写法。
//
// Go 知识点：这个正则是「反引号 raw string + 字符串拼接」拼出来的 ——
// raw string 内不能直接出现反引号，所以字符类里的 ` 用 ` + "`" + ` 嵌入。
var createTableRe = regexp.MustCompile(`(?is)CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[` + "`" + `\"]?([a-zA-Z0-9_]+)[` + "`" + `\"]?\s*\((.*?)\)\s*(?:ENGINE|COMMENT|DEFAULT|;)`)

// genQuerier 生成 *sql.DB 与 *sql.Tx 的公共子集。
//
// 生成的 CRUD 都接收 Querier，于是同一套函数在事务内（Write-Behind 落库）
// 与事务外（登录预加载）都能用，不必为事务再生成一份。
//
// 权威定义在 pkg/flush：flush.FlatOps 的签名需要 Querier，而 model 依赖
// flush（不能反向）。这里只保留别名，30 张表的生成代码零改动。
//
// Go 知识点：`type Querier = flush.Querier` 是类型别名（带等号），
// 不产生新类型，两侧完全可互换；若写成 `type Querier flush.Querier`
// 则是定义新类型，已有代码全部要改。
func genQuerier(outDir string) error {
	const body = `// Code generated by tools/gendb from sql/schema. DO NOT EDIT.

package model

import "game_study/pkg/flush"

// Querier 是 *sql.DB 与 *sql.Tx 的共同子集（两者都满足）。
//
// 权威定义在 pkg/flush（FlatOps 需要它，而 model 依赖 flush 不能反向）；
// 这里保留类型别名，既有生成代码与业务调用点零改动。
type Querier = flush.Querier
`
	return writeGoFile(filepath.Join(outDir, "querier_gen.go"), body)
}

var (
	// commentRe 匹配 -- 行注释。
	// 只处理 -- 行注释：DDL 约定不使用 /* */ 块注释（块注释里的 @flat 不会被识别，
	// 这是约定而非疏漏）。
	commentRe = regexp.MustCompile(`--[^\n]*`)
	// flatRe 匹配建表注释里的 @flat:<模块名> 标注。
	flatRe = regexp.MustCompile(`@flat:([a-zA-Z0-9_]+)`)
)

// flatSuffix 返回日志里的 @flat 标记（无标注为空）。
func flatSuffix(t table) string {
	if t.FlatModule == "" {
		return ""
	}
	return "，@flat:" + t.FlatModule
}

// parseSQL 解析一个 .sql 文件里的全部 CREATE TABLE。
//
// 返回的表携带列、PK 与 @flat:<模块> 标注；@flat 表额外强制「PK 恰为 player_id」，
// 不满足直接返回错误 —— 生成期失败优于生成出编译不过的代码（FindByPK 签名会与
// FlatOps.Load 对不上）。
//
// Go 知识点：FindAllStringSubmatchIndex 返回「子匹配的字节区间」而不是字符串，
// 因此同一组区间可以分别在原文（text，取 @flat 标注）与去注释版（stripped，
// 取 CREATE TABLE）里取串 —— 「标注在注释里、语句在代码里」能对齐比较的关键。
// reservedWords MySQL 8.0 保留字（RESERVED，非关键字）。
//
// 只列「真的会被当成标识符用」的那部分——完整表 200+ 个，但绝大多数
// （SELECT/WHERE/AND 之类）不可能被拿来当列名。这里收的是**表结构里
// 出现过或很可能出现**的：rows 已经踩过（rank_archive_task.rows 让整张表
// 读写了几个月都没成功），rank/order/group/key/status/level/interval/
// window 都是容易顺手写上去的。
//
// 只收 **reserved**：MySQL 的关键字分 reserved（必须加反引号才能当标识符）
// 与 non-reserved（可以直接用）。status / level / system / date / text
// 这些看似危险的都是 non-reserved，现有表用了也没问题，放进来只会误报。
//
// 维护策略：加列时撞到新的保留字（表现为运行时 Error 1064），把那个词补进来。
// 漏一个不可怕——可怕的是「生成物看起来正常、跑起来全错」。
var reservedWords = map[string]bool{
	// MySQL 8.0 新增的窗口函数保留字——最容易被忽略的一类（rows 已经踩过）
	"rows": true, "row": true, "over": true, "window": true,
	"rank": true, "dense_rank": true, "row_number": true, "ntile": true,
	"lead": true, "lag": true, "first_value": true, "last_value": true,
	"nth_value": true, "percent_rank": true, "cume_dist": true,
	"partition": true, "range": true, "preceding": true, "following": true,
	"unbounded": true, "current": true, "recursive": true, "lateral": true,
	"json_table": true, "empty": true, "of": true, "groups": true,
	// 传统保留字里最容易当列名的
	"order": true, "group": true, "key": true, "keys": true,
	"desc": true, "describe": true, "interval": true, "usage": true,
	"condition": true, "match": true, "out": true, "in": true,
	"is": true, "like": true, "between": true, "exists": true,
	"case": true, "when": true, "then": true, "else": true, "end": true,
	"and": true, "or": true, "not": true, "null": true, "true": true,
	"false": true, "default": true, "values": true, "index": true,
	"primary": true, "foreign": true, "references": true,
	"constraint": true, "unique": true,
}

func parseSQL(path string) ([]table, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	text := string(raw)
	// 注释替换为等长空格而不是删除：保留字节偏移，@flat 标注的位置才能与
	// CREATE TABLE 的位置直接比较（删注释会让偏移全部错位）。
	// strings.Repeat(" ", len(m)) 按字节计空白，与正则区间的字节口径一致，
	// 注释含中文时字节数 > 字符数，这里依然正确。
	stripped := commentRe.ReplaceAllStringFunc(text, func(m string) string {
		return strings.Repeat(" ", len(m))
	})
	anns := flatRe.FindAllStringSubmatchIndex(text, -1)
	matches := createTableRe.FindAllStringSubmatchIndex(stripped, -1)
	var tables []table
	prevEnd := 0
	for _, m := range matches {
		t := table{Name: stripped[m[2]:m[3]]}
		// 标注写在本表之前、上一张表结束之后的注释区间里。
		for _, a := range anns {
			if a[0] >= prevEnd && a[1] <= m[0] {
				t.FlatModule = text[a[2]:a[3]]
			}
		}
		prevEnd = m[1]
		for _, line := range strings.Split(stripped[m[4]:m[5]], ",") {
			line = strings.TrimSpace(line)
			if line == "" {
				continue
			}
			// DDL 关键字大小写不敏感（PRIMARY KEY / primary key 都合法），统一转大写后匹配。
			// 每行只 ToUpper 一次，后面的 HasPrefix/Contains 全部复用 up；
			// 生成的 SQL 保持 DDL 原样大小写，不受这次转换影响
			up := strings.ToUpper(line)
			if strings.HasPrefix(up, "PRIMARY KEY") {
				t.PKs = pkCols(line)
				continue
			}
			// 索引/约束子句不是列定义，跳过（UNIQUE KEY 也以 KEY 开头，一并覆盖）
			if strings.HasPrefix(up, "UNIQUE") || strings.HasPrefix(up, "KEY") ||
				strings.HasPrefix(up, "INDEX") || strings.HasPrefix(up, "CONSTRAINT") ||
				strings.HasPrefix(up, "FOREIGN") {
				continue
			}
			fields := strings.Fields(line)
			if len(fields) < 2 {
				// DDL 列定义形如 `id` bigint NOT NULL，前两段必然是列名与类型；
				// 不足两段的是残缺行，跳过而不是报错（容错草稿 DDL）
				continue
			}
			c := column{
				Name:    strings.Trim(fields[0], "`\""),
				SQLType: strings.ToLower(fields[1]),
			}
			// 保留字检查：生成的 SQL 不给列名加反引号，撞上 MySQL 保留字就是
			// 语法错误（Error 1064），而且生成物本身看不出来。必须在生成阶段拦。
			if reservedWords[c.Name] {
				return nil, fmt.Errorf("表 %s 的列名 %q 是 MySQL 保留字：生成的 SQL 不加反引号，"+
					"运行时会报 Error 1064。请换个名字（如 rows → archived_rows）", t.Name, c.Name)
			}
			c.GoName = upperCamel(c.Name)
			c.GoType = goType(c.SQLType)
			c.AutoInc = strings.Contains(up, "AUTO_INCREMENT")
			c.NotNull = strings.Contains(up, "NOT NULL")
			// DEFAULT CURRENT_TIMESTAMP（created_at/updated_at）：写入时由 DB 生成，
			// 不传 Go 零值时间（time.Time{} = 0001-01-01 会超出 TIMESTAMP/DATETIME 范围，
			// MySQL 报 1292 Incorrect datetime value，集成测试实测复现）
			c.AutoTime = strings.Contains(up, "DEFAULT CURRENT_TIMESTAMP")
			t.Columns = append(t.Columns, c)
		}
		if len(t.PKs) == 0 {
			// 回退：自增列或第一列当 PK。
			// 为什么需要回退：省略 PRIMARY KEY 子句的 DDL 也必须生成
			// FindByPK/UpdateByPK 的 WHERE 子句；取自增列是第一优先（MySQL 惯例），
			// 否则退第一列 —— 宁可要一个「大概对」的主键，也不生成跑不起来的代码。
			for _, c := range t.Columns {
				if c.AutoInc {
					t.PKs = []string{c.Name}
					break
				}
			}
			if len(t.PKs) == 0 && len(t.Columns) > 0 {
				t.PKs = []string{t.Columns[0].Name}
			}
		}
		// PK 列表 → 集合：下面给每列打 IsPK 标记时 O(1) 查询，
		// 列数 * PK 数的双重循环退化成一次遍历
		pkSet := map[string]bool{}
		for _, p := range t.PKs {
			pkSet[p] = true
		}
		for i := range t.Columns {
			t.Columns[i].IsPK = pkSet[t.Columns[i].Name]
		}
		// 标注即契约：单行状态表的主键必须恰为 player_id，否则 FindByPK 的
		// 签名与 FlatOps.Load 不匹配，宁可在生成期报错也不生成跑不起来的代码。
		if t.FlatModule != "" && (len(t.PKs) != 1 || t.PKs[0] != "player_id") {
			return nil, fmt.Errorf("%s: @flat:%s 要求主键恰为 (player_id)，实际为 (%s)",
				t.Name, t.FlatModule, strings.Join(t.PKs, "+"))
		}
		tables = append(tables, t)
	}
	return tables, nil
}

// pkCols 从 `PRIMARY KEY (a, b)` 行提取列名（去空白与引号，多列主键按 DDL 顺序）。
//
// 顺序必须保持 DDL 声明顺序：pkParams/pkWhere 生成的形参表与 WHERE 子句
// 都按这个顺序展开，调用方传参顺序依赖它。
func pkCols(line string) []string {
	i := strings.Index(line, "(")
	j := strings.LastIndex(line, ")")
	if i < 0 || j < 0 || j <= i {
		return nil
	}
	var cols []string
	for _, p := range strings.Split(line[i+1:j], ",") {
		cols = append(cols, strings.Trim(strings.TrimSpace(p), "`\""))
	}
	return cols
}

// goType SQL 类型 → Go 类型（列常量/结构体/扫描目标的类型唯一来源）。
//
// 映射约定：tinyint(1) → bool（布尔语义优先于整型，必须先判带参形式）；
// bigint → int64；int/smallint/tinyint → int32；decimal/float/double → float64
// （浮点有精度损失，金额字段若要精确需另行约定 decimal+string）；
// datetime/timestamp/date → time.Time；其余（varchar/text/json/enum）→ string。
//
// Go 知识点：switch 的一个 case 用逗号并列多个条件是「或」语义，比多个 case
// 落同一组语句简洁；且第一个匹配的 case 生效 —— 所以「tinyint(1) 特殊判定」
// 必须排在通用 tinyint 之前，顺序即优先级。
func goType(sqlType string) string {
	base := sqlType
	if i := strings.Index(base, "("); i > 0 {
		base = base[:i]
	}
	switch {
	case strings.HasPrefix(sqlType, "tinyint(1)"):
		return "bool"
	case strings.HasPrefix(base, "bigint"):
		return "int64"
	case strings.HasPrefix(base, "int"), strings.HasPrefix(base, "smallint"):
		return "int32"
	case strings.HasPrefix(base, "tinyint(1)"):
		return "bool"
	case strings.HasPrefix(base, "tinyint"):
		return "int32"
	case strings.HasPrefix(base, "decimal"), strings.HasPrefix(base, "float"), strings.HasPrefix(base, "double"):
		return "float64"
	case strings.HasPrefix(base, "datetime"), strings.HasPrefix(base, "timestamp"), strings.HasPrefix(base, "date"):
		return "time.Time"
	default: // varchar/text/json/enum...
		return "string"
	}
}

// genModel 生成一张表的 <table>_gen.go：结构体 + 列常量 + TableName + 单行 CRUD
// + 批量/按玩家读写 + （可选）@flat FlatOps 适配。
//
// 全量覆盖写盘（设计文档 16.4 约定禁止手改）；自定义查询放同名 <table>_model.go，
// 由生成器仅首次创建，不被覆盖。
//
// 与 gendata 一样用 strings.Builder 拼接而非 text/template：模板的空白控制
// 会让产物对无关改动也产生整片 diff，而这里所有分支（有无时间列、有无批量列、
// 是否 @flat）用 Go 的 if 表达比模板的 {{if}} 更易读，最后统一 format.Source 兜底。
func genModel(outDir string, t table) error {
	tn := upperCamel(t.Name) // 导出标识符统一走 CamelCase（account → Account）
	var b strings.Builder
	b.WriteString("// Code generated by tools/gendb from sql/schema. DO NOT EDIT.\n")
	b.WriteString("// " + t.Name + " 表 CRUD（覆盖策略见设计文档 16.4）\n\n")
	b.WriteString("package model\n\n")
	// import 按需生成：ctx/*sql.DB 恒定需要；time 仅当存在时间列（strings 从不使用，不引入）。
	// 先扫一遍列类型再决定 import：生成物若 import 了没使用的包，
	// go build 直接报错 —— 生成器必须自己对「 import 完备性」负责
	needTime := false
	for _, c := range t.Columns {
		if c.GoType == "time.Time" {
			needTime = true
		}
	}
	b.WriteString("import (\n\t\"context\"\n\t\"database/sql\"\n")
	if needTime {
		b.WriteString("\t\"time\"\n")
	}
	b.WriteString("\n\t\"game_study/pkg/flush\"\n)\n\n")

	// 结构体
	b.WriteString("// " + tn + " " + t.Name + " 表\n")
	b.WriteString("type " + tn + " struct {\n")
	for _, c := range t.Columns {
		b.WriteString("\t" + c.GoName + " " + goFieldType(c) + " `db:\"" + c.Name + "\"`\n")
	}
	b.WriteString("}\n\n")

	// 列常量
	b.WriteString("// " + tn + " 列名\n")
	b.WriteString("const (\n")
	for _, c := range t.Columns {
		b.WriteString("\tCol" + tn + upperCamel(c.Name) + " = \"" + c.Name + "\"\n")
	}
	b.WriteString(")\n\n")

	// TableName
	b.WriteString("// TableName 表名\n")
	b.WriteString("func (m *" + tn + ") TableName() string { return \"" + t.Name + "\" }\n\n")

	// Columns 列表
	b.WriteString("// " + tn + "Columns 全部列（扫描用）\n")
	b.WriteString("var " + tn + "Columns = []string{\n")
	for _, c := range t.Columns {
		b.WriteString("\tCol" + tn + upperCamel(c.Name) + ",\n")
	}
	b.WriteString("}\n\n")

	// Insert：列 = 全部列排除 DB 生成时间列（保留自增 PK：显式 Id 落库时保留，
	// Id 为零值时 MySQL 自增列特性把 0 替换为下一个自增值，行为与跳过一致）
	insCols := upsertCols(t)
	if len(insCols) > 0 {
		// ?,?,? 占位符按列数生成：Repeat 造 n 个 "?," 再去掉尾部逗号，
		// 比循环拼接少一次中间字符串分配；列序与 names/argsOf 严格一致
		ph := strings.TrimSuffix(strings.Repeat("?,", len(insCols)), ",")
		names := colNames(insCols)
		b.WriteString("// Insert 插入（自增列由数据库生成）\n")
		b.WriteString("func Insert" + tn + "(ctx context.Context, db Querier, m *" + tn + ") (sql.Result, error) {\n")
		b.WriteString("\treturn db.ExecContext(ctx, \"INSERT INTO " + t.Name + " (" + strings.Join(names, ",") + ") VALUES (" + ph + ")\", " + argsOf(insCols) + ")\n")
		b.WriteString("}\n\n")
	}

	// FindByPK
	b.WriteString("// Find" + tn + "ByPK 按主键查询\n")
	b.WriteString("func Find" + tn + "ByPK(ctx context.Context, db Querier, " + pkParams(t) + ") (*" + tn + ", error) {\n")
	b.WriteString("\tvar m " + tn + "\n")
	b.WriteString("\tquery := \"SELECT " + strings.Join(colNames(t.Columns), ",") + " FROM " + t.Name + " WHERE " + pkWhere(t) + "\"\n")
	b.WriteString("\trow := db.QueryRowContext(ctx, query, " + pkArgNames(t) + ")\n")
	b.WriteString("\tif err := scan" + tn + "(&m, row); err != nil {\n\t\treturn nil, err\n\t}\n\treturn &m, nil\n}\n\n")

	// scan 辅助：把「一行 → Scan 目标列表」收敛成一个函数，单行（QueryRowContext）
	// 与多行（Query.Next 循环）复用同一份 &m.X 列表，避免两处列序不一致
	b.WriteString("func scan" + tn + "(m *" + tn + ", sc interface{ Scan(...any) error }) error {\n")
	b.WriteString("\treturn sc.Scan(" + scanTargets(t) + ")\n")
	b.WriteString("}\n\n")

	// UpdateByPK（更新非 PK 列）
	updCols := nonPKNonAutoCols(t)
	if len(updCols) > 0 {
		sets := make([]string, 0, len(updCols))
		for _, c := range updCols {
			sets = append(sets, c.Name+" = ?")
		}
		b.WriteString("// Update" + tn + "ByPK 按主键更新（幂等）\n")
		b.WriteString("func Update" + tn + "ByPK(ctx context.Context, db Querier, m *" + tn + ") (sql.Result, error) {\n")
		b.WriteString("\treturn db.ExecContext(ctx, \"UPDATE " + t.Name + " SET " + strings.Join(sets, ", ") + " WHERE " + pkWhere(t) + "\", " + argsOf(updCols) + ", " + pkArgNamesOfM(t) + ")\n")
		b.WriteString("}\n\n")

		// UpsertByPK（INSERT ... ON DUPLICATE KEY UPDATE）
		// INSERT 列 = 全部列（含自增 PK）：显式指定 Id 时靠 PK 唯一键冲突触发 UPDATE 分支；
		// Id 为零值时 MySQL 自增列特性会把 0 替换为下一个自增值，行为不变。
		// 若 INSERT 跳过自增 PK，ON DUPLICATE 永不命中，Upsert 退化为纯 INSERT（幂等失效）。
		b.WriteString("// Upsert" + tn + "ByPK 插入或更新（落库幂等，18.2 防线②）\n")
		b.WriteString("func Upsert" + tn + "ByPK(ctx context.Context, db Querier, m *" + tn + ") (sql.Result, error) {\n")
		updSet := make([]string, 0, len(updCols))
		for _, c := range updCols {
			updSet = append(updSet, c.Name+" = VALUES("+c.Name+")")
		}
		upsCols := upsertCols(t) // 全部列（含自增 PK），排除 DB 生成时间列
		phAll := strings.TrimSuffix(strings.Repeat("?,", len(upsCols)), ",")
		b.WriteString("\treturn db.ExecContext(ctx, \"INSERT INTO " + t.Name + " (" + strings.Join(colNames(upsCols), ",") + ") VALUES (" + phAll + ") ON DUPLICATE KEY UPDATE " + strings.Join(updSet, ", ") + "\", " + argsOf(upsCols) + ")\n")
		b.WriteString("}\n\n")
	}

	// DeleteByPK
	b.WriteString("// Delete" + tn + "ByPK 按主键删除\n")
	b.WriteString("func Delete" + tn + "ByPK(ctx context.Context, db Querier, " + pkParams(t) + ") (sql.Result, error) {\n")
	b.WriteString("\treturn db.ExecContext(ctx, \"DELETE FROM " + t.Name + " WHERE " + pkWhere(t) + "\", " + pkArgNames(t) + ")\n")
	b.WriteString("}\n")

	// 批量落库与按玩家读取：Write-Behind 的模块 Persister 只需要这几个函数，
	// 表名/列名/占位符全部来自生成物，业务代码里不再出现 SQL 字符串。
	hasBatch := false
	if upsCols := batchUpsertCols(t); len(upsCols) > 0 {
		hasBatch = true
		colsVar := "upsert" + tn + "Cols"
		b.WriteString("\n// " + colsVar + " 批量 UPSERT 使用的列（不含 DB 生成的时间列）\n")
		b.WriteString("var " + colsVar + " = []string{" + quotedList(colNames(upsCols)) + "}\n\n")
		b.WriteString("// Upsert" + tn + "Batch 事务内批量插入或更新（Write-Behind 落库用）\n")
		b.WriteString("func Upsert" + tn + "Batch(ctx context.Context, tx *sql.Tx, rows []" + tn + ") error {\n")
		b.WriteString("\treturn flush.UpsertBatch(ctx, tx, \"" + t.Name + "\", " + colsVar + ", rows, func(m " + tn + ") []any {\n")
		b.WriteString("\t\treturn []any{" + argsOf(upsCols) + "}\n")
		b.WriteString("\t})\n}\n\n")
	}
	if pcol := playerColumn(t); pcol != "" {
		b.WriteString("// Delete" + tn + "ByPlayer 删除该玩家全部行（整包替换落库用）\n")
		b.WriteString("func Delete" + tn + "ByPlayer(ctx context.Context, tx *sql.Tx, playerID int64) error {\n")
		b.WriteString("\treturn flush.DeleteByPlayer(ctx, tx, \"" + t.Name + "\", \"" + pcol + "\", playerID)\n")
		b.WriteString("}\n\n")
		b.WriteString("// List" + tn + "ByPlayer 按玩家列出全部行（冷启动读取用）\n")
		b.WriteString("func List" + tn + "ByPlayer(ctx context.Context, db Querier, playerID int64) ([]" + tn + ", error) {\n")
		b.WriteString("\trows, err := db.QueryContext(ctx, \"SELECT " + strings.Join(colNames(t.Columns), ",") + " FROM " + t.Name + " WHERE " + pcol + " = ?\", playerID)\n")
		b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n\tdefer func() { _ = rows.Close() }()\n")
		b.WriteString("\tvar out []" + tn + "\n")
		b.WriteString("\tfor rows.Next() {\n\t\tvar m " + tn + "\n\t\tif err := scan" + tn + "(&m, rows); err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\tout = append(out, m)\n\t}\n")
		b.WriteString("\treturn out, rows.Err()\n}\n")
	}

	// @flat 标注：生成 FlatOps 适配，模块侧一行 writebehind.RegisterFlat 即可完成持久化接入。
	if t.FlatModule != "" {
		if !hasBatch {
			return fmt.Errorf("%s: @flat:%s 的表没有可批量写入的列", t.Name, t.FlatModule)
		}
		b.WriteString("\n// " + tn + "Flat " + t.FlatModule + " 模块的单行状态表适配（sql 注释 @flat:" + t.FlatModule + " 生成）\n")
		b.WriteString("var " + tn + "Flat = flush.FlatOps[" + tn + "]{\n")
		b.WriteString("\tUpsert: Upsert" + tn + "Batch,\n")
		b.WriteString("\tLoad:   Find" + tn + "ByPK,\n")
		b.WriteString("}\n")
	}

	path := filepath.Join(outDir, t.Name+"_gen.go")
	return writeGoFile(path, pruneUnusedFlushImport(b.String()))
}

// pruneUnusedFlushImport 在没有生成任何 flush.* 调用时去掉 flush 导入。
//
// 为什么需要：像 map_id_allocator 这种「只有自增主键 + DB 生成时间列」的表，
// 没有可更新列（nonPKNonAutoCols 为空），因此不会生成 Update/Upsert/Flat，
// 也就不会引用 flush。而 import 是提前写死的，Go 编译期报「导入未使用」，
// 整个 pkg/model 都编不过。
//
// 判定方式：import 行本身是 "game_study/pkg/flush"（不含 "flush."），
// 所以正文里出现 "flush." 就说明确实用到了；一次 Contains 即可判定，
// 不需要解析 AST（生成器保持零依赖、纯字符串拼接的风格）。
func pruneUnusedFlushImport(src string) string {
	if strings.Contains(src, "flush.") {
		return src
	}
	return strings.Replace(src, "\n\t\"game_study/pkg/flush\"", "", 1)
}

// goFieldType 列的 Go 字段类型：自增列恒为 int64；可空时间列用 sql.NullTime
// （写入零值为 NULL，避免 time.Time{} 超出 TIMESTAMP/DATETIME 范围报 1292；
// 读出 NULL 也不报 "converting NULL to time.Time is unsupported"）。
//
// 自增列恒为 int64 而不按 SQL 类型：MySQL 自增列可以是 int，但 Go 侧主键
// 统一 int64 后与 robot/gamedata 的 Id int64 口径一致，省去各处类型转换。
func goFieldType(c column) string {
	if c.AutoInc {
		return "int64"
	}
	if c.GoType == "time.Time" && !c.NotNull {
		// 可空时间列（如 expire_at/paid_at）：sql.NullTime 同时根治两个问题——
		// ① 写入零值不越界（Valid=false → NULL）；② 读出 NULL 不报
		// "converting NULL to time.Time is unsupported"
		return "sql.NullTime"
	}
	return c.GoType
}

// upsertCols Upsert 的 INSERT 列：保留自增 PK（显式 Id 幂等命中唯一键），
// 排除 DB 生成时间列（created_at/updated_at 由 DEFAULT/ON UPDATE 维护）
func upsertCols(t table) []column {
	var out []column
	for _, c := range t.Columns {
		if !c.AutoTime {
			out = append(out, c)
		}
	}
	return out
}

// nonPKNonAutoCols Update 的 SET 列：排除 PK、自增列与 DB 生成时间列
// （updated_at 依赖 DDL 的 ON UPDATE CURRENT_TIMESTAMP 自动维护）
func nonPKNonAutoCols(t table) []column {
	var out []column
	for _, c := range t.Columns {
		if !c.IsPK && !c.AutoInc && !c.AutoTime {
			out = append(out, c)
		}
	}
	return out
}

// batchUpsertCols 批量 UPSERT 的列：排除 DB 生成时间列与自增主键。
//
// 与单行 UpsertByPK 的取舍不同 —— 单行场景调用方可能显式给了 Id，靠 PK 冲突
// 触发 UPDATE；批量掉库的行由模块从内存快照组装，自增列恒为零值，带上它只会
// 白白消耗自增值。冲突判定交给业务唯一键（如 uk_player_sign_day）。
func batchUpsertCols(t table) []column {
	out := make([]column, 0, len(t.Columns))
	for _, c := range t.Columns {
		if c.AutoTime || c.AutoInc {
			continue
		}
		out = append(out, c)
	}
	return out
}

// colNames 列切片 → 列名切片（SQL 语句拼接用，顺序与入参一致）。
func colNames(cols []column) []string {
	out := make([]string, 0, len(cols))
	for _, c := range cols {
		out = append(out, c.Name)
	}
	return out
}

// argsOf 生成 `m.Xxx, m.Yyy` 形式的实参列表（与列顺序一一对应，供 ExecContext 用）。
func argsOf(cols []column) string {
	out := make([]string, 0, len(cols))
	for _, c := range cols {
		out = append(out, "m."+c.GoName)
	}
	return strings.Join(out, ", ")
}

// pkParams 生成 `Id int64` 形式的形参列表（Find/Delete ByPK 用）。
// 多列主键按 DDL 声明顺序展开，调用方传参顺序必须与之一致。
func pkParams(t table) string {
	var out []string
	for _, p := range t.PKs {
		var goName, goType string
		for _, c := range t.Columns {
			if c.Name == p {
				goName, goType = c.GoName, c.GoType
			}
		}
		out = append(out, goName+" "+goType)
	}
	return strings.Join(out, ", ")
}

// pkArgNamesOfM 同 pkArgNames，但带 m. 前缀（用于只有 m 参数的 Update）
func pkArgNamesOfM(t table) string {
	var out []string
	for _, p := range t.PKs {
		for _, c := range t.Columns {
			if c.Name == p {
				out = append(out, "m."+c.GoName)
			}
		}
	}
	return strings.Join(out, ", ")
}

// pkArgNames 生成 `Id` 形式的实参列表（Find/Delete ByPK 用，与 pkParams 一一对应）。
func pkArgNames(t table) string {
	var out []string
	for _, p := range t.PKs {
		for _, c := range t.Columns {
			if c.Name == p {
				out = append(out, c.GoName)
			}
		}
	}
	return strings.Join(out, ", ")
}

// pkWhere 生成 `id = ? AND player_id = ?` 形式的 WHERE 子句（多列主键 AND 连接）。
func pkWhere(t table) string {
	var out []string
	for _, p := range t.PKs {
		out = append(out, p+" = ?")
	}
	return strings.Join(out, " AND ")
}

// scanTargets 生成 `&m.Xxx, ...` 形式的 Scan 目标列表，
// 顺序必须与 SELECT 的列序一致（SELECT 全部列，因此字段序 = 列序）。
func scanTargets(t table) string {
	out := make([]string, 0, len(t.Columns))
	for _, c := range t.Columns {
		out = append(out, "&m."+c.GoName)
	}
	return strings.Join(out, ", ")
}

// upperCamel snake_case → CamelCase（account_id → AccountId）。
// 表名与列名的导出标识符统一入口（account → Account）。
// 与 gendata 的同名实现同形：两个生成器必须用同一套命名规则，
// 否则同一张表在 model 与 gamedata 里的字段名会对不上。
func upperCamel(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == ' ' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

// quotedList 生成 Go 字符串字面量列表（"a", "b"），用于列名切片。
func quotedList(items []string) string {
	q := make([]string, len(items))
	for i, s := range items {
		q[i] = `"` + s + `"`
	}
	return strings.Join(q, ", ")
}

// playerColumn 判断该表能否「按玩家整包处理」：存在名为 player_id 的列。
//
// 注意不要求它是首列：player_item 这类实体表的首列是自增 id，玩家维度在第二列。
// 没有玩家维度的表（account / guild / team）不生成 ByPlayer 函数。
func playerColumn(t table) string {
	for _, c := range t.Columns {
		if c.Name == "player_id" {
			return "player_id"
		}
	}
	return ""
}

// writeGoFile 生成物统一走 gofmt：未格式化的生成物会让 `make fmt` 与 `make gen-check` 互相打架，
// 而 format.Source 同时充当生成代码的语法检查。
//
// Go 知识点：go/format.Source 是 gofmt 的编程接口（parser + printer 往返），
// 只重排不改语义；解析失败即语法错误，因此这一行是「生成物编译不过」的前哨。
func writeGoFile(path, src string) error {
	out, err := format.Source([]byte(src))
	if err != nil {
		return fmt.Errorf("gofmt %s: %w", filepath.Base(path), err)
	}
	return os.WriteFile(path, out, 0o644)
}

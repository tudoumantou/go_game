// Package crossplay 跨服玩法的中心服侧：报名裁决、分组、积分同步下发。
//
// 数据归属与权威性：
//   - 报名由中心服裁决（报名期校验 + 幂等），成功才让游戏服写本地行；
//   - 分组只在这里算，结果写 center_cross_group，是全局唯一权威；
//   - 积分由各服上报绝对值，中心服合并后按服聚合下发（60s 窗口）。
//
// 中心服不持有玩家存档，也不感知玩家在线状态：积分是玩法数据，
// 改分只需要改这一层，与玩家 Actor 无关（离线玩家照样能被打、被更新）。
//
// 生命周期由活动管理器驱动：报名期收集 → 分组期算一次 → 活动期同步积分。
// 表内不带活动维度（期次由活动管理器持有），切期清表时整体清空。
//
// 规模假设（一期一场）：10 万人 / 100 人一组 = 1000 组。分组是 O(n log n)
// 的内存排序，毫秒级；真正的成本在内存与下发窗口，不在计算。
package crossplay

// GroupSize 每组人数。尾组不足也照样开班（排名玩法不需要等满）。
const GroupSize = 100

// Member 一个参与者的分组视图。
//
// 只保留分组与下发需要的字段：中心服不做展示，昵称/外观这类信息留在游戏服，
// 不进中心服的任何一张表。
type Member struct {
	PlayerID int64
	GroupID  int32 // 0 = 尚未分组
	ServerID int32
	// Power 报名时锁定的战力快照。分组排序依据，活动期内不再更新——
	// 中途换装变强不影响已分好的组，否则「分组公平」无从谈起。
	Power int64
	// Score 活动内积分，初始 1000，随攻击增减。
	Score int64
	// UpdatedAt 最近一次分数变化的 unix 秒（来自玩家所在服的时钟）。
	// 只用于展示排序与排查，不参与任何决策：跨机器时钟不可信。
	UpdatedAt int64
}

// Group 一个组：组号 + 成员（按 Power 降序）。
type Group struct {
	ID      int32
	Members []Member
}

// InitialScore 活动初始积分。
const InitialScore int64 = 1000

// ScoreFloor 分数下限。扣到 600 后不再扣，但仍可被攻击、攻击方仍加分。
//
// 已确认不堵「刷满 600 分玩家」的口子：道具消耗是唯一成本约束。
// 保留 max 语义是因为去掉下限会出现负分，而不是为了防刷。
const ScoreFloor int64 = 600

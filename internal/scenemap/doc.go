// Package scenemap 是 RPG 场景（地图）框架，复刻自 参考实现 版 scene 框架，
// 规格见 docs/场景大地图设计.md。
//
// 它与 internal/worldmap（SLG 大地图）是两套完全独立的子系统：
//
//	worldmap  一张 5000×5000 的大世界，25 个逻辑场景，部队/资源/采集，
//	          坐标是定点整数，状态落 MySQL，玩法是"出征-采集-战斗"。
//	scenemap  一张"可玩的地图"（主城/副本/战场），AOI 视野 + 怪物 AI +
//	          技能结算，坐标是格/像素，状态在内存（副本可丢），
//	          玩法是"进图-移动-打怪-通关"。
//
// 两者都复用 pkg/config、pkg/log 这类叶子包，但互不 import。
//
// # 架构总则（不可换）
//
//	一张可玩的图 = 1 个 AOI Actor（视野与广播）
//	             + 1 个 MGR Actor（站位/AI/战斗结算，唯一权威）
//	             + N 个玩家 Actor（只编排自身，不存场景权威态）
//
// 怪物没有独立进程：它们是 MGR 私有 map 里的数据 + MGR 自投递的延时命令。
// 一怪一 goroutine 会在几百怪时产生 mail 风暴与调度抖动。
//
// # 为什么 AOI 与 MGR 必须分开
//
//	视野/广播  高频、只读、可并行 → 独立 Actor，不与结算抢串行队列
//	站位/结算  串行、强一致       → 收口在单 Actor，一只怪结算到一半不能被打断
//
// # 目录职责
//
//	grid      纯函数：像素↔格、距离、范围、阻挡、寻路。无状态、可并发调用。
//	mgr       场景权威：状态、格子索引、实体进出、换格、四定时器、关图计时。
//	aoi       视野：九宫格视野、出现/消失/移动广播、视野快照。
//	room      全局单例：房间登记表、关房收口、节点宕机通知。
//	entity    怪物/召唤/子弹的数据与 AI 状态机（全部活在 MGR 内）。
//	battle    技能战斗结算：Sprite/SkillContext、伤害公式链、选目标、Buff、
//	          死亡链幂等、双回路事件（算法库，不持有 goroutine）。
//	gameplay  玩法插件：每种地图类型一个实现（Loop/PlayerEnter/...）。
//	examples  最小可跑示例：多线主城 + 副本房。
//
// # 并发铁律
//
//   - 每个 Actor 一个 mailbox，状态只由自己的 goroutine 写；
//   - 跨 Actor 只读走「不可变快照 + atomic.Pointer」，不加锁、不做 RPC；
//   - 定时器自续期，间隔过倍速；
//   - 命名注册表是全局并发安全单例；
//   - call 必须有超时与 panic 恢复。

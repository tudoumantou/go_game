// Package view 实现 SLG 大地图的 AOI 投影与视野流（设计文档第 12 章）。
//
// # 分层与依赖方向
//
// runtime 定义 ProjectionSink/ProjectionBatch（"投影出口"的窄接口），
// 本包实现该接口。依赖方向固定为 view → runtime，runtime 绝不 import view：
// 场景循环只认识"发布一批变更键"这件事，不需要知道有多少订阅者、
// 谁的视野覆盖了哪个块、序列化后多大。这样 M2 换实现（比如改成
// 独立的 AOIWorker 进程）时，runtime 一行都不用改。
//
// # 为什么投影只带键，详情在 Flush 时回查
//
// runtime.ProjectionBatch 只携带 Enters/Updates/Leaves 的 ObjectKey，
// 不带对象业务字段。原因不是"省带宽"这么简单，而是正确性：
//
//   - 批次是异步的。场景提交事务 A（对象位置 x=10）后投递批次 A，
//     紧接着提交事务 B（x=20）投递批次 B。如果批次里带业务字段，
//     两个批次排队/网络乱序时，客户端可能先收到 B 再收到 A，
//     最终停在 x=10——投影与权威状态长期不一致。
//   - 只带键的批次等价于"失效通知"（invalidation）。消费方在真正
//     生成事件的那一刻回查权威状态，永远拿最新值；多次变更自然合并，
//     迟到批次也不会把旧值写回视图。这叫水平触发（level-triggered）
//     投影，语义是"最终渲染成当前状态"，而不是"重放每一条变更"。
//   - 回查由 Server 层注入的 Loader 完成（M1 用内存替身，M2 从
//     store 读已提交快照）。角色详情（部队/资源点字段）不参与路由，
//     路由只需要位置与种类，所以索引本身很轻。
//
// 代价是 Flush 时需要一次/多次 LoadObject。M2 应在 Loader 内部做
// 批量查询或读本地只读副本，本包保证"同一键一轮只查一次"。
//
// # 一致性边界
//
//   - SceneView 只保证最终态正确，不承诺把中间态逐条推给客户端；
//     文档 12.3 明确"单对象 update 可以在刷新周期内合并为最后一个版本"。
//   - 订阅者落后超过 MaxResyncGap、或积压超过 ViewPendingBytes 时，
//     投递 Resync 让客户端清缓存重来（文档 12.6），而不是丢几条
//     增量后继续——静默丢增量会让视野永远缺一块。
//   - 本包不参与部队行军、采集归属、战斗裁决（文档 12.4），
//     失效时重新订阅/拉快照即可，不影响业务。
//
// # 并发模型
//
// Coordinator 的 TryPublish 由各场景循环并发调用，只做"有界队列
// 非阻塞投递"；每个 SceneView 一个 goroutine 串行消费队列并 Flush。
// SceneView 内部的块索引、订阅集合、积压计数都由 mu 保护，Flush
// 期间不会做阻塞 I/O（详情回查在锁外完成），避免拖慢其他订阅者。

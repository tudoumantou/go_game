// Package flush 落库调度框架：把内存里的变更攒起来、合并、写库。
//
// 两个粒度，按「键有多少、周期多长」选：
//
//	Flusher   (flusher.go)     大量键 + 长周期（玩家 5K、60s）：分片错峰，
//	                           把整服的写压力摊到一分钟里的不同时刻；
//	Coalescer (coalesce.go)    少量键 + 短周期（房间 10 个、1s）：只做
//	                           键级合并，写失败的键放回集合等下一轮。
//
// 两者共用同一套「合并 -> 写库 -> 失败重试」语义，区别只在调度方式：
// 分片错峰是为了摊平尖峰，键级合并是为了消掉重复写。选错的代价很具体——
// 给 10 个房间上分片错峰是空转，给 5K 玩家只做键级合并会在整点攒出一次
// 写入风暴。
//
// 能力：
//   - 分片调度与批量 UPSERT（flusher.go：10 分片错峰轮询，攒批窗口内
//     多个玩家的写合并为少量多行 INSERT … ON DUPLICATE KEY UPDATE）；
//   - 键级合并落库（coalesce.go：同键一个窗口只写最后态，失败重试不覆盖新意图）；
//   - 单行表工具 FlatOps（flat.go：玩家级单行状态表的读写适配）；
//   - 合批 SQL 构建（batch.go）与事务内执行（exec.go）；
//   - Querier 抽象（querier.go：同时接受 *sql.DB 与 *sql.Tx）；
//   - 墓碑删除（delete.go：业务删除登记为墓碑，落库周期合批物理删除）。
//
// 协作关系：业务 Actor 修改玩家数据后调 Flusher.MarkDirty(playerID)，
// 分片 worker 到点调 PersistFunc（通常由 pkg/writebehind 提供）完成写库；
// 进程退出时 FlushAll 同步排空。非玩家键的合并落库（抢位置的房间快照）
// 走 Coalescer，接口同形：Mark 登记、Stop 排空。
//
// 设计取舍见各文件头（攒批窗口、分片错峰、墓碑削峰、合并重试），核心是
// 「用延迟换吞吐」：允许数据在内存里多待一个周期，换取语句数与数据库
// 往返的成倍下降。
